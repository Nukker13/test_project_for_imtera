/**
 * Коды ошибок парсера → человеческие формулировки.
 *
 * Требование ТЗ: ошибки должны ясно давать понять, в чём проблема. Коды
 * рождаются в Python-сервисе, проходят через parse_runs и попадают сюда —
 * пользователь видит «Яндекс показал капчу», а не HTTP-статус.
 */
const MESSAGES = {
  INVALID_URL: 'Ссылка не похожа на карточку организации в Яндекс.Картах.',
  ORG_NOT_FOUND: 'Организация по этой ссылке не найдена — возможно, ссылка устарела.',
  BLOCKED_CAPTCHA:
    'Яндекс заблокировал запрос: показана капча или сработало ограничение по частоте. Попробуйте позже.',
  SIGNATURE_MISMATCH:
    'Яндекс изменил алгоритм подписи запросов — парсер требует обновления.',
  LAYOUT_CHANGED:
    'Разметка страницы Яндекс.Карт изменилась, парсер не смог найти нужные данные.',
  UPSTREAM_TIMEOUT: 'Яндекс не ответил за отведённое время. Попробуйте ещё раз.',
  PARSER_UNAVAILABLE:
    'Сервис парсинга недоступен. Проверьте, что контейнер python-service запущен.',
  JOB_FAILED: 'Прогон прервался до завершения.',
  INTERNAL_ERROR: 'Внутренняя ошибка при обработке результата.',
}

export function describeError(code, fallback) {
  if (code && MESSAGES[code]) return MESSAGES[code]
  return fallback || 'Неизвестная ошибка.'
}

/** Причина, по которой пришлось переключиться на запасной способ сбора. */
export function describeFallback(reason) {
  const reasons = {
    PAGE_BLOCKED: 'страница была заблокирована, сессию получили через браузер',
    SIGNATURE_MISMATCH: 'подпись запросов не принята, отзывы собраны браузером',
    BLOCKED_CAPTCHA: 'прямые запросы заблокированы, отзывы собраны браузером',
    UPSTREAM_TIMEOUT: 'прямые запросы не отвечали, отзывы собраны браузером',
  }
  return reasons[reason] || 'использован запасной способ сбора'
}
